// Builds Magi's distributable artefacts.
//
//   node build/build.mjs          -> dist/magi.cjs + dist/magi-cli.cjs
//   node build/build.mjs --exe    -> also attempts a standalone executable (see below)
//
// public/ (including the webfonts) is compiled into the bundle, so the app code, assets and
// Express are all inlined. The ONE runtime dependency left external is the SQLCipher driver
// (better-sqlite3-multiple-ciphers) — a native .node module that can't be inlined — so its
// node_modules folder must sit alongside the bundle (the Dockerfile and packaging copy it).
//
// --exe uses Node's Single Executable Application support. That requires postject to
// rewrite the ELF, which is currently broken for Node 26 on this toolchain (a plain
// hello-world SEA segfaults too), so the build verifies the result and refuses to ship
// a binary that does not run.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, copyFileSync, rmSync, chmodSync } from 'node:fs';
import { join, dirname, relative, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'dist');
const BUILD = join(ROOT, 'build');
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const wantExe = process.argv.includes('--exe');

const MIME = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8', '.woff2': 'font/woff2', '.svg': 'image/svg+xml',
  '.png': 'image/png', '.ico': 'image/x-icon', '.json': 'application/json',
};

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out); else out.push(p);
  }
  return out;
}

// ---- 1. compile public/ into a module -------------------------------------
console.log('  [1/3] embedding public/');
const files = walk(join(ROOT, 'public'));
let mod = '// GENERATED by build/build.mjs — do not edit.\nconst assets = {\n';
let bytes = 0;
for (const f of files) {
  const url = '/' + relative(join(ROOT, 'public'), f).split(/[\\/]/).join('/');
  const buf = readFileSync(f);
  bytes += buf.length;
  mod += `  ${JSON.stringify(url)}: { type: ${JSON.stringify(MIME[extname(f)] || 'application/octet-stream')},`
       + ` body: Buffer.from(${JSON.stringify(buf.toString('base64'))}, 'base64') },\n`;
}
mod += '};\n'
  + '// set during this module\'s own evaluation, so it is in place before server.js runs\n'
  + 'globalThis.__MAGI_ASSETS = assets;\nexport default assets;\n';
mkdirSync(BUILD, { recursive: true });
writeFileSync(join(BUILD, 'assets.gen.js'), mod);
// bundle entry: pull the assets in first, then the app
writeFileSync(join(BUILD, 'entry.server.js'),
  "// GENERATED by build/build.mjs — do not edit.\nimport './assets.gen.js';\nimport '../server.js';\n");
console.log(`        ${files.length} files, ${(bytes / 1024).toFixed(0)} KB`);

// ---- 2. bundle ------------------------------------------------------------
console.log('  [2/3] bundling');
mkdirSync(OUT, { recursive: true });
const esbuild = join(ROOT, 'node_modules/.bin/esbuild');
function bundleOne(entry, outfile) {
  execFileSync(esbuild, [
    entry, '--bundle', '--platform=node', '--format=cjs', '--target=node22',
    '--external:node:*', '--legal-comments=none',
    // The SQLCipher driver is a native module (.node) and can't be inlined — leave it as a
    // runtime require(), resolved from node_modules shipped alongside the bundle.
    '--external:better-sqlite3-multiple-ciphers',
    // CJS has no import.meta; map it onto a banner-provided const so fileURLToPath()
    // and createRequire() keep working inside the bundle.
    '--define:import.meta.url=__magiUrl',
    '--banner:js=const __magiUrl = require("node:url").pathToFileURL(__filename).href;',
    '--outfile=' + outfile,
  ], { stdio: ['ignore', 'ignore', 'inherit'] });
  console.log(`        ${relative(ROOT, outfile)}  ${(statSync(outfile).size / 1024).toFixed(0)} KB`);
}
const serverOut = join(OUT, 'magi.cjs');        // standalone: starts the HTTP server
const cliOut = join(OUT, 'magi-cli.cjs');       // standalone: the CLI
const embedOut = join(OUT, 'magi-server.cjs');  // exports the Express app for the desktop app
bundleOne(join(BUILD, 'entry.server.js'), serverOut);
bundleOne(join(ROOT, 'cli.js'), cliOut);
bundleOne(join(ROOT, 'server.js'), embedOut);

// ---- 3. optional standalone executable ------------------------------------
if (!wantExe) {
  console.log('\n  Bundles ready. Package them with:  makepkg -f   (see packaging/PKGBUILD)');
  console.log('  Standalone executable:  node build/build.mjs --exe\n');
  process.exit(0);
}

console.log('  [3/3] standalone executable');
const seaConfig = join(BUILD, 'sea-config.json');
writeFileSync(seaConfig, JSON.stringify({
  main: serverOut, output: join(BUILD, 'sea-prep.blob'),
  disableExperimentalSEAWarning: true, useSnapshot: false, useCodeCache: false,
}, null, 2));
execFileSync(process.execPath, ['--experimental-sea-config', seaConfig], { stdio: ['ignore', 'ignore', 'inherit'] });

const exe = join(OUT, 'magi');
rmSync(exe, { force: true });
copyFileSync(process.execPath, exe);
chmodSync(exe, 0o755);
const { inject } = await import(join(ROOT, 'node_modules/postject/dist/api.js'));
await inject(exe, 'NODE_SEA_BLOB', readFileSync(join(BUILD, 'sea-prep.blob')), {
  sentinelFuse: 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2',
});
rmSync(join(BUILD, 'sea-prep.blob'), { force: true });

// Verify rather than trust: a postject-mangled binary segfaults rather than erroring.
// The server does not exit on its own, so being killed by the timeout means it booted.
let ok = false;
try {
  execFileSync(exe, [], {
    timeout: 6000, stdio: ['ignore', 'pipe', 'pipe'],
    env: { ...process.env, MAGI_PORT: '45999', MAGI_DB: join(BUILD, 'smoke.db') },
  });
} catch (e) {
  ok = e.signal === 'SIGTERM';        // still running when we pulled the plug
  if (!ok) console.error(`        crashed: signal=${e.signal} status=${e.status}`);
}
rmSync(join(BUILD, 'smoke.db'), { force: true });
rmSync(join(BUILD, 'smoke.db-wal'), { force: true });
rmSync(join(BUILD, 'smoke.db-shm'), { force: true });
if (!ok) {
  rmSync(exe, { force: true });
  console.error(`\n  ! The executable does not run, so it was removed rather than shipped.`);
  console.error(`    postject cannot patch this Node build — a hello-world SEA segfaults too.`);
  console.error(`    Use the Arch package instead:  cd packaging && makepkg -f\n`);
  process.exit(1);
}
console.log(`\n  dist/magi  ·  ${(statSync(exe).size / 1048576).toFixed(1)} MB\n`);
